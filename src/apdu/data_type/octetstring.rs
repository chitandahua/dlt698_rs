// 定长OctetString
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct FixedOctetString<const N: usize>([u8; N]);

impl<const N: usize> FixedOctetString<N> {
    pub fn new(data: [u8; N]) -> Self {
        Self(data)
    }

    pub fn from_slice(slice: &[u8]) -> Result<Self, TryFromSliceError> {
        Ok(Self(<[u8; N]>::try_from(slice)?))
    }

    pub fn from_vec(vec: Vec<u8>) -> Result<Self, TryFromSliceError> {
        Self::from_slice(&vec)
    }

    pub fn as_slice(&self) -> &[u8] {
        &self.0
    }

    pub fn into_array(self) -> [u8; N] {
        self.0
    }
}

impl<const N: usize> AsRef<[u8]> for FixedOctetString<N> {
    fn as_ref(&self) -> &[u8] {
        &self.0
    }
}

impl<const N: usize> FromAxdr<'_> for FixedOctetString<N> {
    fn from_axdr(bytes: &[u8]) -> ParseResult<Self> {
        if bytes.len() < N {
            return Err(asn1_rs::Err::Error(Error::InvalidLength));
        }

        Ok((
            &bytes[N..],
            FixedOctetString::<N>::new(bytes[0..N].try_into().unwrap()),
        ))
    }
}

impl<const N: usize> ToAxdr for FixedOctetString<N> {
    fn to_axdr_len(&self) -> Result<usize> {
        Ok(N)
    }

    fn write_axdr_header(&self, _writer: &mut dyn std::io::Write) -> SerializeResult<usize> {
        Ok(0)
    }

    fn write_axdr_content(&self, writer: &mut dyn std::io::Write) -> SerializeResult<usize> {
        writer.write(self.as_ref()).map_err(Into::into)
    }
}

// 变长OctetString
#[derive(Debug, PartialEq, Eq)]
pub struct OctetString<'a> {
    data: Cow<'a, [u8]>,
}

impl<'a> OctetString<'a> {
    pub const fn new(s: &'a [u8]) -> Self {
        OctetString {
            data: Cow::Borrowed(s),
        }
    }

    pub fn as_cow(&'a self) -> &'a Cow<'a, [u8]> {
        &self.data
    }

    pub fn into_cow(self) -> Cow<'a, [u8]> {
        self.data
    }
}

impl AsRef<[u8]> for OctetString<'_> {
    fn as_ref(&self) -> &[u8] {
        &self.data
    }
}

impl<'a> From<&'a [u8]> for OctetString<'a> {
    fn from(b: &'a [u8]) -> Self {
        OctetString {
            data: Cow::Borrowed(b),
        }
    }
}

impl<'a> FromAxdr<'a> for OctetString<'a> {
    fn from_axdr(bytes: &'a [u8]) -> ParseResult<'a, Self> {
        let (bytes, int) = UnsignedInteger::from_axdr(bytes)?;
        let len = int.as_u64()? as usize; // TODO BigInt?

        if bytes.len() < len {
            return Err(asn1_rs::Err::Error(Error::InvalidLength));
        }

        Ok((&bytes[len..], OctetString::new(&bytes[0..len])))
    }
}

