use crate::{Error, ParseResult, Result, SerializeResult};
use core::convert::TryFrom;
use std::array::TryFromSliceError;

// 定长OctetString
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct FixedOctetString<const N: usize>([u8; N]);

impl<const N: usize> FixedOctetString<N> {
    pub fn new(data: [u8; N]) -> Self {
        Self(data)
    }

    pub fn from_slice(slice: &[u8]) -> Result<Self, TryFromSliceError> {
        Ok(Self(<[u8; N]>::try_from(slice)?))
    }

    pub fn from_vec(vec: Vec<u8>) -> Result<Self, TryFromSliceError> {
        Self::from_slice(&vec)
    }

    pub fn as_slice(&self) -> &[u8] {
        &self.0
    }

    pub fn into_array(self) -> [u8; N] {
        self.0
    }
}

impl<const N: usize> AsRef<[u8]> for FixedOctetString<N> {
    fn as_ref(&self) -> &[u8] {
        &self.0
    }
}

impl<const N: usize> FromAxdr<'_> for FixedOctetString<N> {
    fn from_axdr(bytes: &[u8]) -> ParseResult<Self> {
        if bytes.len() < N {
            return Err(asn1_rs::Err::Error(Error::InvalidLength));
        }

        Ok((
            &bytes[N..],
            FixedOctetString::<N>::new(bytes[0..N].try_into().unwrap()),
        ))
    }
}

impl<const N: usize> ToAxdr for FixedOctetString<N> {
    fn to_axdr_len(&self) -> Result<usize> {
        Ok(N)
    }

    fn write_axdr_header(&self, _writer: &mut dyn std::io::Write) -> SerializeResult<usize> {
        Ok(0)
    }

    fn write_axdr_content(&self, writer: &mut dyn std::io::Write) -> SerializeResult<usize> {
        writer.write(self.as_ref()).map_err(Into::into)
    }
}

// 变长OctetString
#[derive(Debug, PartialEq, Eq)]
pub struct OctetString {
    data: Vec<u8>,
}

impl OctetString {
    pub fn new(s: &[u8]) -> Self {
        OctetString { data: s.to_vec() }
    }

    pub fn into_vec(self) -> Vec<u8> {
        self.data
    }
}

impl AsRef<[u8]> for OctetString {
    fn as_ref(&self) -> &[u8] {
        self.data.as_slice()
    }
}

impl From<&[u8]> for OctetString {
    fn from(b: &[u8]) -> Self {
        OctetString { data: b.to_vec() }
    }
}

impl FromAxdr<'_> for OctetString {
    fn from_axdr(bytes: &[u8]) -> ParseResult<Self> {
        let (bytes, int) = UnsignedInteger::from_axdr(bytes)?;
        let len = int.as_usize()?;

        if bytes.len() < len {
            return Err(asn1_rs::Err::Error(Error::InvalidLength));
        }

        Ok((&bytes[len..], OctetString::new(&bytes[0..len])))
    }
}

impl ToAxdr for OctetString {
    fn to_axdr_len(&self) -> Result<usize> {
        Ok(UnsignedInteger::from_usize(self.as_ref().len()).to_axdr_len()? + self.as_ref().len())
    }

    fn write_axdr_header(&self, writer: &mut dyn std::io::Write) -> SerializeResult<usize> {
        UnsignedInteger::from_usize(self.as_ref().len()).write_axdr(writer)
    }

    fn write_axdr_content(&self, writer: &mut dyn std::io::Write) -> SerializeResult<usize> {
        writer.write(self.as_ref()).map_err(Into::into)
    }
}

impl ToAxdr for &'_ [u8] {
    fn to_axdr_len(&self) -> Result<usize> {
        Ok(UnsignedInteger::from_usize(self.len()).to_axdr_len()? + self.len())
    }

    fn write_axdr_header(&self, writer: &mut dyn std::io::Write) -> SerializeResult<usize> {
        UnsignedInteger::from_usize(self.len()).write_axdr(writer) // TODO
    }

    fn write_axdr_content(&self, writer: &mut dyn std::io::Write) -> SerializeResult<usize> {
        writer.write(self).map_err(Into::into)
    }
}

impl<const N: usize> From<FixedOctetString<N>> for OctetString {
    fn from(b: FixedOctetString<N>) -> Self {
        OctetString { data: b.0.to_vec() }
    }
}

